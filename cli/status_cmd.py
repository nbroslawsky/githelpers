"""Status, list, doctor, and enable/disable commands."""

import os
import re
import subprocess
import sys

from .detect import (
    BOLD, CHECK, CROSS, CYAN, GREEN, RED, RESET, WARN, YELLOW,
    detect_all, print_summary, _run, githelpers_dir,
)


CONF_PATH = os.path.expanduser("~/.githelpers.conf")
MODULES = ["aliases", "functions", "prompt", "completions"]


# ── Config helpers ────────────────────────────────────────────────────────

def read_conf():
    """Read ~/.githelpers.conf and return dict of module -> bool."""
    result = {}
    if not os.path.isfile(CONF_PATH):
        return result
    try:
        with open(CONF_PATH, "r") as f:
            for line in f:
                line = line.strip()
                if line.startswith("#") or "=" not in line:
                    continue
                key, _, val = line.partition("=")
                key = key.strip()
                val = val.strip()
                # GITHELPERS_MODULE_ALIASES=1
                m = re.match(r"GITHELPERS_MODULE_(\w+)", key)
                if m:
                    mod = m.group(1).lower()
                    result[mod] = val == "1"
    except OSError:
        pass
    return result


def write_conf(modules):
    """Write ~/.githelpers.conf with module states."""
    lines = ["# Generated by githelpers setup\n"]
    for mod in MODULES:
        val = "1" if modules.get(mod, False) else "0"
        lines.append("GITHELPERS_MODULE_{}={}\n".format(mod.upper(), val))
    with open(CONF_PATH, "w") as f:
        f.writelines(lines)


# ── status ────────────────────────────────────────────────────────────────

def run_status():
    info = detect_all()
    print_summary(info)

    conf = read_conf()
    if not conf:
        print(YELLOW + "No configuration found. Run `githelpers setup` first." + RESET)
        print()
        return

    print(BOLD + "Modules" + RESET)
    for mod in MODULES:
        enabled = conf.get(mod, False)
        marker = CHECK if enabled else CROSS
        label = GREEN + "enabled" + RESET if enabled else RED + "disabled" + RESET
        print("  {} {:<14s} {}".format(marker, mod, label))
    print()

    print(BOLD + "Paths" + RESET)
    print("  Config:      {}".format(CONF_PATH))
    print("  Install dir: {}".format(info["githelpers_dir"]))
    print()


# ── list ──────────────────────────────────────────────────────────────────

def run_list():
    raw = _run(["git", "config", "--get-regexp", "^alias\\."])
    if not raw:
        print(YELLOW + "No git aliases found." + RESET)
        return

    aliases = []
    for line in raw.splitlines():
        # alias.co checkout
        parts = line.split(None, 1)
        if len(parts) == 2:
            name = parts[0].replace("alias.", "")
            cmd = parts[1]
            aliases.append((name, cmd))

    if not aliases:
        print(YELLOW + "No git aliases found." + RESET)
        return

    # Determine column width
    max_name = max(len(a[0]) for a in aliases)
    col = max(max_name + 2, 12)

    print()
    print(BOLD + "Git Aliases" + RESET)
    print("  {}{:<{}}{}".format(CYAN, "Alias", col, "Command" + RESET))
    print("  " + "-" * (col + 40))
    for name, cmd in sorted(aliases):
        # Truncate very long commands for display
        display_cmd = cmd if len(cmd) <= 70 else cmd[:67] + "..."
        print("  {}{:<{}}{}{}".format(GREEN, name, col, RESET, display_cmd))
    print()


# ── doctor ────────────────────────────────────────────────────────────────

def run_doctor():
    info = detect_all()
    ok = True

    print()
    print(BOLD + "githelpers doctor" + RESET)
    print()

    # 1. Git version >= 2.22
    gv = info["git_version"]
    if gv is None:
        print("  {} Git is not installed!".format(CROSS))
        ok = False
    else:
        parts = gv.split(".")
        try:
            major, minor = int(parts[0]), int(parts[1])
        except (IndexError, ValueError):
            major, minor = 0, 0
        if (major, minor) >= (2, 22):
            print("  {} Git version {} (>= 2.22)".format(CHECK, gv))
        else:
            print("  {} Git version {} — 2.22+ recommended".format(WARN, gv))
            ok = False

    # 2. Python version
    pv = sys.version_info
    if pv >= (3, 7):
        print("  {} Python {}.{}.{}".format(CHECK, pv.major, pv.minor, pv.micro))
    else:
        print("  {} Python {}.{}.{} — 3.7+ required".format(CROSS, pv.major, pv.minor, pv.micro))
        ok = False

    # 3. Shell profile has source line
    gh_dir = info["githelpers_dir"]
    source_line = "source {}/shell/githelpers.sh".format(gh_dir)
    shell = info["shell"]
    if shell == "zsh":
        profile = os.path.expanduser("~/.zshrc")
    elif shell == "bash":
        profile = os.path.expanduser("~/.bash_profile") if info["os"] == "macOS" else os.path.expanduser("~/.bashrc")
    else:
        profile = os.path.expanduser("~/.profile")

    if os.path.isfile(profile):
        try:
            with open(profile, "r") as f:
                text = f.read()
            if source_line in text:
                print("  {} Source line present in {}".format(CHECK, profile))
            else:
                print("  {} Source line missing from {}".format(CROSS, profile))
                ok = False
        except OSError:
            print("  {} Cannot read {}".format(CROSS, profile))
            ok = False
    else:
        print("  {} Shell profile not found: {}".format(CROSS, profile))
        ok = False

    # 4. gitconfig include
    gitconfig_path = os.path.join(gh_dir, "gitconfig")
    # Also check for ~/... form since git config often stores paths with ~
    gitconfig_tilde = gitconfig_path.replace(os.path.expanduser("~"), "~", 1)
    includes = _run(["git", "config", "--global", "--get-all", "include.path"])
    if gitconfig_path in includes or gitconfig_tilde in includes:
        print("  {} gitconfig include.path set".format(CHECK))
    else:
        print("  {} gitconfig include.path not set".format(CROSS))
        ok = False

    # 5. Alias conflicts with existing commands
    conflict_count = 0
    raw = _run(["git", "config", "--get-regexp", "^alias\\."])
    if raw:
        import shutil
        for line in raw.splitlines():
            parts = line.split(None, 1)
            if parts:
                name = parts[0].replace("alias.", "")
                if shutil.which(name):
                    print("  {} Alias '{}' shadows an existing command".format(WARN, name))
                    conflict_count += 1
    if conflict_count == 0:
        print("  {} No alias conflicts detected".format(CHECK))

    # 6. Config file
    if os.path.isfile(CONF_PATH):
        print("  {} Config file exists".format(CHECK))
    else:
        print("  {} Config file missing — run `githelpers setup`".format(WARN))

    print()
    if ok:
        print(GREEN + "  All checks passed." + RESET)
    else:
        print(YELLOW + "  Some issues detected — see above." + RESET)
    print()


# ── enable / disable ─────────────────────────────────────────────────────

def run_toggle(module, enable):
    conf = read_conf()
    if not conf and not enable:
        print(YELLOW + "No configuration found. Run `githelpers setup` first." + RESET)
        return

    # Ensure all modules have a value
    for mod in MODULES:
        conf.setdefault(mod, False)

    conf[module] = enable
    write_conf(conf)

    state = GREEN + "enabled" + RESET if enable else RED + "disabled" + RESET
    print("{} Module '{}' {}.".format(CHECK, module, state))
