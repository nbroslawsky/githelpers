"""Interactive setup wizard for githelpers."""

import os
import shutil
import subprocess
import sys

from .detect import (
    BOLD, CHECK, CYAN, GREEN, RED, RESET, WARN, YELLOW,
    detect_all, detect_shell, print_summary,
)


CONF_PATH = os.path.expanduser("~/.githelpers.conf")
MODULES = ["aliases", "functions", "prompt", "completions"]


# ── Helpers ───────────────────────────────────────────────────────────────

def _ask(question, default_yes=True):
    """Prompt user with [Y/n] or [y/N]. Returns True/False."""
    suffix = " [Y/n] " if default_yes else " [y/N] "
    try:
        answer = input(BOLD + question + RESET + suffix).strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        sys.exit(1)
    if answer == "":
        return default_yes
    return answer in ("y", "yes")


def _shell_profile(info):
    """Return the path to the user's shell profile file."""
    shell = info["shell"]
    if shell == "zsh":
        return os.path.expanduser("~/.zshrc")
    if shell == "bash":
        if info["os"] == "macOS":
            return os.path.expanduser("~/.bash_profile")
        return os.path.expanduser("~/.bashrc")
    # Fallback: try .profile
    return os.path.expanduser("~/.profile")


def _backup(path):
    """Create a timestamped backup of a file."""
    if not os.path.isfile(path):
        return
    import time
    ts = time.strftime("%Y%m%d%H%M%S")
    backup = "{}.githelpers-backup-{}".format(path, ts)
    shutil.copy2(path, backup)
    print("  {} Backed up {} -> {}".format(CHECK, path, backup))


def _file_contains(path, needle):
    """Check if a file contains a string."""
    if not os.path.isfile(path):
        return False
    try:
        with open(path, "r") as f:
            return needle in f.read()
    except OSError:
        return False


def _write_conf(modules):
    """Write ~/.githelpers.conf with enabled/disabled modules."""
    lines = ["# Generated by githelpers setup\n"]
    for mod in MODULES:
        val = "1" if modules.get(mod, False) else "0"
        lines.append("GITHELPERS_MODULE_{}={}\n".format(mod.upper(), val))
    with open(CONF_PATH, "w") as f:
        f.writelines(lines)
    print("  {} Wrote {}".format(CHECK, CONF_PATH))


# ── Main setup flow ──────────────────────────────────────────────────────

def run_setup():
    info = detect_all()

    print()
    print(BOLD + CYAN + "=== githelpers setup ===" + RESET)
    print_summary(info)

    gh_dir = info["githelpers_dir"]
    gitconfig_path = os.path.join(gh_dir, "gitconfig")
    source_line = "source {}/shell/githelpers.sh".format(gh_dir)

    modules = {}

    # 1. Git aliases (gitconfig include)
    print("  Git aliases: co, st, ci, lg, branches, wip, and more")
    modules["git_aliases"] = _ask("Install git aliases?", default_yes=True)

    # 2. Shell aliases (g=git, gs, gco …) — opt-in
    print("  Shell shortcuts: g=git, gs='git st', gco='git co', gd='git diff', etc.")
    modules["aliases"] = _ask("Install shell aliases?", default_yes=False)

    # 3. Helper functions
    print("  Functions: git_cleanup_branches, git_open, git_search_replace, etc.")
    modules["functions"] = _ask("Install helper functions?", default_yes=True)

    # 3. Prompt
    fw = info["prompt_framework"]
    if fw != "none":
        print("  {} Prompt framework detected: {}{}{}. Skipping prompt setup.".format(
            WARN, CYAN, fw, RESET))
        modules["prompt"] = False
    else:
        modules["prompt"] = _ask("Install git prompt integration?", default_yes=True)

    # 4. Completions
    if info["git_completions"]:
        print("  {} Git completions already available. Skipping.".format(WARN))
        modules["completions"] = False
    else:
        modules["completions"] = _ask("Install git completions?", default_yes=True)

    # ── Write config ──────────────────────────────────────────────────
    print()
    print(BOLD + "Applying changes..." + RESET)

    # Extract git_aliases flag (not a shell module — controls gitconfig include)
    install_git_aliases = modules.pop("git_aliases", True)

    _write_conf(modules)

    # ── Git aliases via include.path ──────────────────────────────────
    if install_git_aliases:
        try:
            subprocess.run(
                ["git", "config", "--global", "include.path", gitconfig_path],
                check=True,
            )
            print("  {} Set gitconfig include.path -> {}".format(CHECK, gitconfig_path))
        except subprocess.CalledProcessError as exc:
            print("  {} Failed to set gitconfig include: {}".format(RED + "!" + RESET, exc))

    # ── Shell profile ─────────────────────────────────────────────────
    profile = _shell_profile(info)
    if _file_contains(profile, source_line):
        print("  {} Source line already present in {}".format(WARN, profile))
    else:
        _backup(profile)
        with open(profile, "a") as f:
            f.write("\n# githelpers\n{}\n".format(source_line))
        print("  {} Added source line to {}".format(CHECK, profile))

    # ── Done ──────────────────────────────────────────────────────────
    print()
    print(BOLD + GREEN + "Setup complete!" + RESET)
    print()
    print("Restart your shell or run:")
    print("  {}source {}{}".format(CYAN, profile, RESET))
    print()
